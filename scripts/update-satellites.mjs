// Fetches satellite orbital data (TLEs) from Celestrak and writes it to
// js/satellite-data.js for the Reporting page's client-side sky report.
// Celestrak's endpoint doesn't allow browser CORS, so this has to run
// server-side (see .github/workflows/update-news.yml) rather than being
// fetched directly by the visitor's browser.
import { writeFile } from "node:fs/promises";

const REQUEST_HEADERS = { "User-Agent": "Mozilla/5.0 ParalnoiaSatelliteBot/1.0 (+https://github.com/jimrbrodie/Building_Paralnoia)" };

const GROUPS = {
  iss: "https://celestrak.org/NORAD/elements/gp.php?CATNR=25544&FORMAT=tle",
  visual: "https://celestrak.org/NORAD/elements/gp.php?GROUP=visual&FORMAT=tle",
  starlink: "https://celestrak.org/NORAD/elements/gp.php?GROUP=starlink&FORMAT=tle",
};

// Starlink alone is 7000+ satellites — propagating all of them client-side
// on every report would be slow, so cap how many TLEs we keep.
const MAX_STARLINK = 400;

function parseTle(text) {
  const lines = text.trim().split("\n").map((l) => l.trim()).filter(Boolean);
  const sats = [];
  for (let i = 0; i + 2 < lines.length + 1; i += 3) {
    const name = lines[i];
    const line1 = lines[i + 1];
    const line2 = lines[i + 2];
    if (!name || !line1 || !line2 || !line1.startsWith("1 ") || !line2.startsWith("2 ")) continue;
    sats.push({ name: name.trim(), line1, line2 });
  }
  return sats;
}

async function fetchGroup(url) {
  try {
    const res = await fetch(url, { headers: REQUEST_HEADERS });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    return parseTle(await res.text());
  } catch (err) {
    console.error(`Failed to fetch ${url}: ${err.message}`);
    return [];
  }
}

async function main() {
  const [iss, visual, starlinkFull] = await Promise.all([
    fetchGroup(GROUPS.iss),
    fetchGroup(GROUPS.visual),
    fetchGroup(GROUPS.starlink),
  ]);

  const starlink = starlinkFull.slice(0, MAX_STARLINK);

  const satelliteData = {
    updatedAt: new Date().toISOString(),
    iss,
    visual,
    starlink,
    starlinkSampleOf: starlinkFull.length,
  };

  const fileContents = `// AUTO-GENERATED by scripts/update-satellites.mjs via .github/workflows/update-news.yml
// Do not edit by hand — changes will be overwritten on the next scheduled run.
const satelliteData = ${JSON.stringify(satelliteData, null, 2)};
`;

  await writeFile(new URL("../js/satellite-data.js", import.meta.url), fileContents, "utf-8");
  console.log(`Wrote ${iss.length} ISS, ${visual.length} visual, ${starlink.length}/${starlinkFull.length} Starlink TLEs.`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
